"""Dev-only: export the MonoBehaviour typetrees the patcher needs (TMP_FontAsset, TMP_Dropdown) to data/typetrees.json.

Requires dummy DLLs generated by Cpp2IL (`--output-as dummydll --use-processor attributeanalyzer,attributeinjector`).
usage: export_typetrees.py <dummydll_dir> <out.json>
"""
import sys, json
from UnityPy.helpers.TypeTreeGenerator import TypeTreeGenerator

dll_dir, out = sys.argv[1:3]
gen = TypeTreeGenerator("2021.3.45f2")
gen.load_local_dll_folder(dll_dir)
result = {}
for cls in ("TMPro.TMP_FontAsset", "TMPro.TMP_Dropdown"):
    nodes = gen.get_nodes("Unity.TextMeshPro.dll", cls)
    result[cls] = [[n.m_Level, n.m_Type, n.m_Name, n.m_MetaFlag] for n in nodes]
json.dump(result, open(out, "w", encoding="utf-8"), indent=0)
print({k: len(v) for k, v in result.items()})
